#!/usr/bin/env python3
"""Simple VRML 3D models (boxes and cylinders, datasheet dimensions) for the
parts whose KiCad library has no model: the panel connectors, pots, toggle,
side-view LEDs and the 1812 fuse.  They only make the 3D renders and the
enclosure fit check complete; they are not used for manufacturing.

Writes ../hardware/lib/ld405.3dshapes/*.wrl.  Model space: mm / 2.54 (KiCad's
VRML unit is 0.1 inch), x right, y = -footprint y, z up from the board.
"""
import math, os

HERE = os.path.dirname(os.path.abspath(__file__))
DIR = os.path.normpath(os.path.join(HERE, "..", "hardware", "lib", "ld405.3dshapes"))
U = 1 / 2.54

SILVER, NICKEL, BLACK, WHITE, RED = (0.78, 0.79, 0.8), (0.65, 0.66, 0.68), (0.08, 0.08, 0.09), (0.93, 0.93, 0.9), (0.75, 0.12, 0.15)
GOLD, CLEAR, GREEN = (0.85, 0.68, 0.25), (0.88, 0.95, 1.0), (0.2, 0.45, 0.3)


class Model:
    def __init__(self, name):
        self.name = name
        self.shapes = []          # (rgb, verts, faces) for the VRML file
        self.prims = []           # ("box", rgb, x0, y0, z0, x1, y1, z1) / ("cyl", rgb, p0, p1, r)

    def mesh(self, rgb, verts, faces):
        self.shapes.append((rgb, verts, faces))

    def box(self, rgb, x0, y0, z0, x1, y1, z1):
        """Footprint coordinates (y down); converted to model space here."""
        self.prims.append(("box", rgb, min(x0, x1), min(y0, y1), min(z0, z1), max(x0, x1), max(y0, y1), max(z0, z1)))
        # model y = -footprint y: list y1 first so model y increases with the index
        v = [(x, -y, z) for z in (z0, z1) for y in (y1, y0) for x in (x0, x1)]
        f = [(0, 2, 3, 1), (4, 5, 7, 6), (0, 1, 5, 4), (2, 6, 7, 3), (0, 4, 6, 2), (1, 3, 7, 5)]
        self.mesh(rgb, v, f)

    def cyl(self, rgb, p0, p1, r, n=32):
        """Cylinder from p0 to p1 (footprint coordinates x, y, z)."""
        self.prims.append(("cyl", rgb, tuple(p0), tuple(p1), r))
        a = [p0[0], -p0[1], p0[2]]
        b = [p1[0], -p1[1], p1[2]]
        d = [b[i] - a[i] for i in range(3)]
        L = math.sqrt(sum(c * c for c in d))
        w = [c / L for c in d]
        t = (1, 0, 0) if abs(w[0]) < 0.9 else (0, 1, 0)
        u = [w[1] * t[2] - w[2] * t[1], w[2] * t[0] - w[0] * t[2], w[0] * t[1] - w[1] * t[0]]
        un = math.sqrt(sum(c * c for c in u)); u = [c / un for c in u]
        v2 = [w[1] * u[2] - w[2] * u[1], w[2] * u[0] - w[0] * u[2], w[0] * u[1] - w[1] * u[0]]
        verts = []
        for base in (a, b):
            for k in range(n):
                th = 2 * math.pi * k / n
                verts.append(tuple(base[i] + r * (math.cos(th) * u[i] + math.sin(th) * v2[i]) for i in range(3)))
        faces = [(k, (k + 1) % n, n + (k + 1) % n, n + k) for k in range(n)]
        faces.append(tuple(range(n - 1, -1, -1)))
        faces.append(tuple(range(n, 2 * n)))
        self.mesh(rgb, verts, faces)

    def save(self):
        name = self.name
        os.makedirs(DIR, exist_ok=True)
        lines = ["#VRML V2.0 utf8", f"# {name}: simplified model generated by tools/gen_3d.py"]
        for rgb, verts, faces in self.shapes:
            pts = ", ".join(f"{x * U:.4f} {y * U:.4f} {z * U:.4f}" for x, y, z in verts)
            idx = ", ".join(" ".join(str(i) for i in f) + " -1" for f in faces)
            lines.append("Shape { appearance Appearance { material Material { diffuseColor %.3f %.3f %.3f "
                         "specularColor 0.3 0.3 0.3 shininess 0.4 } }" % rgb)
            lines.append("  geometry IndexedFaceSet { solid FALSE creaseAngle 0.6")
            lines.append(f"    coord Coordinate {{ point [ {pts} ] }}")
            lines.append(f"    coordIndex [ {idx} ] }} }}")
        path = os.path.join(DIR, name + ".wrl")
        with open(path, "w") as f:
            f.write("\n".join(lines) + "\n")
        return path


def bnc():
    """DOSIN-801-0080: origin = centre contact, panel towards -x, axis 9.8 mm up."""
    m = Model("BNC_DOSIN_801-0080")
    m.box(NICKEL, -5, -5, 0, 5, 5, 15)
    z = 9.8
    m.cyl(NICKEL, (-6, 0, z), (-5, 0, z), 7)              # round flange (panel stop)
    m.cyl(SILVER, (-14, 0, z), (-6, 0, z), 6)             # M12 x 0.75 thread
    m.cyl(SILVER, (-24.5, 0, z), (-14, 0, z), 4.8)        # bayonet sleeve
    m.cyl(WHITE, (-24.6, 0, z), (-21, 0, z), 3.4)         # insulator
    m.cyl(GOLD, (-24.7, 0, z), (-22, 0, z), 0.6)          # contact
    for y in (-4.8, 4.8):
        m.cyl(SILVER, (-19.5, y, z), (-19.5, y * 1.12, z), 0.5)   # bayonet studs
    return m


def toggle():
    """1MS1T2B4M7QES (Dailywell M7: right-angle PC terminals, vertical bracket).
    Origin = bracket legs, panel towards -x.  From the drawing: bushing Ø6.22 x 7.31,
    lever reaching 6.46 beyond the bushing, body 10.1 long x 12.7 high x 6.86 wide,
    terminals leave the back at 2.3 / 6.5 / 10.9 mm (1 lowest) and bend down at
    12.70 / 16.51 / 20.32 mm.  The drawing gives no axis height: measured 6.45 mm.
    Lever drawn up (= ENABLE in this design)."""
    m = Model("Toggle_Dailywell_1MS1T2B4M7QES")
    z = 6.45
    m.box(SILVER, -0.76, -3.43, -2.6, 0, 3.43, 12.7)          # bracket and its legs
    m.box(RED, 0, -3.43, 0, 10.1, 3.43, 12.7)                  # body
    m.cyl(SILVER, (-7.31, 0, z), (0, 0, z), 3.11)              # unthreaded 1/4" bushing
    a = math.radians(18)
    tip = (-7.31 - 6.46, 0, z + 6.46 * math.tan(a))
    m.cyl(SILVER, (-6.5, 0, z), tip, 1.0)                      # lever
    m.cyl(SILVER, (tip[0] + 0.6, 0, tip[2] - 0.2), (tip[0] - 0.4, 0, tip[2] + 0.13), 1.33)
    for x, h in ((12.70, 2.3), (16.51, 6.5), (20.32, 10.9)):
        m.box(SILVER, 10.1, -0.4, h - 0.38, x + 0.38, 0.4, h + 0.38)     # out of the back
        m.box(SILVER, x - 0.38, -0.4, -3.18, x + 0.38, 0.4, h + 0.38)    # down through the board
    return m


def dcjack():
    """DC-005: origin = front face centre on the board edge, plug from -x; body 14 x 9 x 11,
    plug axis 7.0 mm up (4.0 mm below the top)."""
    m = Model("BarrelJack_DC-005_Horizontal")
    m.box(BLACK, 0, -4.5, 0, 14, 4.5, 11)
    m.cyl((0.02, 0.02, 0.02), (-0.05, 0, 7.0), (0.3, 0, 7.0), 3.1)
    m.cyl(SILVER, (0.0, 0, 7.0), (8, 0, 7.0), 1.0)          # centre pin (visible in the hole)
    return m


def led():
    """Lite-On LTST-S220: body 2.15 x 0.6 x 1.0, lens towards -x, origin = body centre."""
    m = Model("LED_SideView_LTST-S220")
    m.box(WHITE, -0.3, -1.075, 0, 0.3, 1.075, 1.0)
    m.box(CLEAR, -0.75, -0.85, 0.1, -0.3, 0.85, 0.9)          # lens
    for y0, y1 in ((-1.075, -0.745), (0.745, 1.075)):
        m.box(SILVER, -0.32, y0, 0, 0.32, y1, 1.0)            # tin-plated terminals
    m.box(GREEN, 0.3, 0.45, 0.2, 0.32, 0.7, 0.8)              # cathode mark
    return m


def pot():
    """Alps RK09L horizontal (KiCad footprint origin = pad 1); shaft towards -x
    at footprint y = 2.5, 6.5 mm above the board."""
    m = Model("Potentiometer_Alps_RK09L_Single_Horizontal")
    y, z = 2.5, 6.5
    m.box(BLACK, -4.6, -3.55, 0, 2.45, 8.55, 11.35)          # body
    m.box(SILVER, -5.0, -3.55, 0, -4.6, 8.55, 11.6)           # front frame
    m.cyl(SILVER, (-10, y, z), (-5, y, z), 4.5)               # M9 x 0.75 bushing
    m.cyl(SILVER, (-20, y, z), (-10, y, z), 3.0)              # 6 mm shaft
    return m


def jack35():
    """PJ-320D (KiCad footprint Jack_3.5mm_KoreanHropartsElec_PJ-320D-4A origin);
    opening towards -x, axis 2.5 mm up."""
    m = Model("Jack_3.5mm_PJ-320D")
    m.box(BLACK, -6.35, -3.05, 0, 5.75, 3.05, 5.0)
    m.cyl(BLACK, (-8.35, 0, 2.5), (-6.35, 0, 2.5), 2.5)
    m.cyl((0.0, 0.0, 0.0), (-8.4, 0, 2.5), (-7.0, 0, 2.5), 1.8)
    return m


def fuse1812():
    m = Model("Fuse_1812_4532Metric")
    m.box(GREEN, -2.25, -1.6, 0, 2.25, 1.6, 1.1)
    for x0, x1 in ((-2.25, -1.75), (1.75, 2.25)):
        m.box(SILVER, x0, -1.6, 0, x1, 1.6, 1.12)
    return m


